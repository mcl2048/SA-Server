// The authoritative shared definition owns biographies and hatchling species
// traits. Individual battle skill lists always come from the server's PetInfo.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export function syncPrimalClawsCatalog() {
  const data = JSON.parse(readFileSync(join(root, "server/internal/data/primal_claws.json"), "utf8"));
  const identities = [["cyrufas","萨鲁法斯",199400,29007,32017,"50,0,0,50"],["claudes","克劳德斯",199401,29008,32016,"0,50,50,0"]];
  if (data.skill?.ID !== 29060 || data.skill?.Func !== "PETSKILL_PrimalCross" || data.skill?.Target !== 1 || !Array.isArray(data.pets) || data.pets.length !== 2) throw Error("Invalid primal claw catalogue identity");
  const records = data.pets.map((p,i) => {
    const [key,name,image,temp,floor,attrs] = identities[i];
    if (p.key !== key || p.name !== name || p.image !== image || p.temp !== temp || p.floor !== floor
      || typeof p.story !== "string" || !p.story || ![p.x,p.y].every(Number.isInteger)
      || !Array.isArray(p.base) || p.base.length !== 4 || !p.base.every(Number.isFinite) || p.base.reduce((a,b)=>a+b,0) !== 124
      || p.initNum !== 40 || p.lvUpPoint !== 4 || !Array.isArray(p.attr) || p.attr.join(",") !== attrs
      || !Array.isArray(p.skills) || !p.skills.includes(29060)) throw Error("Invalid primal claw catalogue identity");
    return {key:p.key,sprite:p.image,temp:p.temp,name:p.name,story:p.story,brief:p.story.split("。")[0]+"。",base:p.base,attrs:p.attr,floor:p.floor,x:p.x,y:p.y,skills:p.skills};
  });
  const content = `// Generated by scripts/sync-primal-claws-catalog.mjs from server/internal/data/primal_claws.json.\n// Edit the shared JSON, then regenerate; no server file is fetched by the browser.\nimport type { AiPetCatalogEntry } from "./ai-pet-catalog.ts";\n\nexport const PRIMAL_CLAWS_CATALOG: readonly AiPetCatalogEntry[] = ${JSON.stringify(records,null,2)};\n`;
  const path = join(root,"client/src/primal-claws-catalog.ts");
  let before="";try{before=readFileSync(path,"utf8");}catch(e){if(e.code!=="ENOENT")throw e;}
  if(content!==before)writeFileSync(path,content);
  return records.length;
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url))console.log(`已同步 ${syncPrimalClawsCatalog()} 只赤爪宠物的客户端图鉴资料`);
