// Keep the browser catalogue aligned with the embedded server definition.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export function syncAiPetCatalog() {
  const definition = JSON.parse(readFileSync(join(root, "server/internal/data/ai_pets.json"), "utf8"));
  const records = definition.pets.map(p => ({
    key: p.key, sprite: p.image, temp: p.temp, name: p.name, story: p.story,
    brief: p.story.split("。")[0] + "。", base: p.base, attrs: p.attr,
    floor: p.floor, x: p.x, y: p.y, skills: p.skills,
  }));
  if (records.length !== 4 || new Set(records.map(p => p.sprite)).size !== 4
    || records.some((p, i) => p.sprite !== 199100 + i || p.temp !== 29001 + i || !p.name || !p.story)) throw Error("Invalid AI pet catalogue identities");
  const content = `// Generated by scripts/sync-ai-pet-catalog.mjs from server/internal/data/ai_pets.json.\n// Edit the shared JSON, then regenerate; no server file is fetched by the browser.\nexport interface AiPetCatalogEntry {\n  readonly key: string; readonly sprite: number; readonly temp: number; readonly name: string;\n  readonly story: string; readonly brief: string; readonly base: readonly number[]; readonly attrs: readonly number[];\n  readonly floor: number; readonly x: number; readonly y: number; readonly skills: readonly number[];\n}\nexport const AI_PET_CATALOG: readonly AiPetCatalogEntry[] = ${JSON.stringify(records, null, 2)};\n\nexport function aiPetForSprite(sprite: number): AiPetCatalogEntry | undefined {\n  return AI_PET_CATALOG.find(p => p.sprite === sprite);\n}\n`;
  const output = join(root, "client/src/ai-pet-catalog.ts");
  let previous = "";
  try { previous = readFileSync(output, "utf8"); } catch (error) { if (error.code !== "ENOENT") throw error; }
  if (content !== previous) writeFileSync(output, content);
  return records.length;
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(`已同步 ${syncAiPetCatalog()} 只新宠物的客户端图鉴资料`);
}
