// Lilith is an independent extension; the original four-pet catalogue and its
// stable identities remain untouched. The browser never fetches server files.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export function syncLilithCatalog() {
  const p = JSON.parse(readFileSync(join(root, "server/internal/data/lilith.json"), "utf8"));
  if (p.image !== 199200 || p.temp !== 29005 || p.name !== "莉莉丝" || typeof p.story !== "string" || !p.story
    || !Array.isArray(p.base) || p.base.length !== 4 || !p.base.every(Number.isFinite) || p.base.reduce((a, b) => a + b, 0) !== 149
    || !Array.isArray(p.attr) || p.attr.join(",") !== "0,0,20,80"
    || !Array.isArray(p.skills) || !p.skills.includes(29040)
    || ![p.floor, p.x, p.y].every(Number.isInteger)) throw Error("Invalid Lilith catalogue identity");
  const record = { key: p.key, sprite: p.image, temp: p.temp, name: p.name, story: p.story,
    brief: p.story.split("。")[0] + "。", base: p.base, attrs: p.attr, floor: p.floor, x: p.x, y: p.y, skills: p.skills };
  const content = `// Generated by scripts/sync-lilith-catalog.mjs from server/internal/data/lilith.json.\n// Edit the shared JSON, then regenerate; no server file is fetched by the browser.\nimport type { AiPetCatalogEntry } from "./ai-pet-catalog.ts";\n\nexport const LILITH_CATALOG: AiPetCatalogEntry = ${JSON.stringify(record, null, 2)};\n`;
  const output = join(root, "client/src/lilith-catalog.ts");
  let previous = "";
  try { previous = readFileSync(output, "utf8"); } catch (error) { if (error.code !== "ENOENT") throw error; }
  if (content !== previous) writeFileSync(output, content);
  return 1;
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) console.log(`已同步 ${syncLilithCatalog()} 只莉莉丝的客户端图鉴资料`);
