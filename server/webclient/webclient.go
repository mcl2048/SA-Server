// Package webclient serves only the built browser application. Game assets remain
// external, independently configured data and are never included in this FS.
package webclient

import (
	"bytes"
	"compress/gzip"
	"crypto/sha256"
	"embed"
	"fmt"
	"io/fs"
	"net/http"
	"os"
	"strconv"
	"strings"
	"time"
)

// The marker keeps ordinary source checkouts buildable. A release must run
// scripts/build-linux.sh, which stages index.html and dist before go build.
//
//go:embed all:static
var bundled embed.FS

// Handler uses the bundled release client when external is empty. A nonempty
// path explicitly selects an external built client with the same URL allowlist.
func Handler(external string) http.Handler {
	var files fs.FS
	if external != "" {
		files = os.DirFS(external)
	} else {
		files, _ = fs.Sub(bundled, "static")
	}
	return handler(files, external == "")
}

func published(name string) bool {
	if name != "index.html" && name != "art/login.png" && !(strings.HasPrefix(name, "dist/") && strings.HasSuffix(name, ".js")) {
		return false
	}
	for _, part := range strings.Split(name, "/") {
		if part == "" || strings.HasPrefix(part, ".") || strings.Contains(part, "\\") {
			return false
		}
	}
	return fs.ValidPath(name)
}

type clientFile struct {
	content []byte
	etag    string
	gzip    []byte
}

func readClientFile(files fs.FS, name string) (clientFile, error) {
	content, err := fs.ReadFile(files, name)
	// The weak validator identifies decoded content across identity/gzip variants.
	return clientFile{content: content, etag: fmt.Sprintf(`W/"%x"`, sha256.Sum256(content))}, err
}

// These limits cover only additional compressed copies. Published embedded
// originals were already cached; no Assets file is loaded by this handler.
const maxGzipCacheBytes = 4 << 20
const maxGzipFileBytes = 2 << 20

func compressedClientFile(content []byte, remaining int) []byte {
	if len(content) == 0 || len(content) > maxGzipFileBytes || remaining <= 0 {
		return nil
	}
	var encoded bytes.Buffer
	writer, err := gzip.NewWriterLevel(&encoded, gzip.BestSpeed)
	if err != nil {
		return nil // Compression is optional; identity and streaming remain valid.
	}
	_, writeErr := writer.Write(content)
	closeErr := writer.Close()
	if writeErr != nil || closeErr != nil || encoded.Len() >= len(content) || encoded.Len() > remaining {
		return nil
	}
	// Copy the finished stream so the cache does not retain Buffer's spare
	// capacity; the payload budget is independent of compression growth steps.
	return bytes.Clone(encoded.Bytes())
}

func varyEncoding(header http.Header) {
	for _, value := range header.Values("Vary") {
		for _, field := range strings.Split(value, ",") {
			if field = strings.TrimSpace(field); field == "*" || strings.EqualFold(field, "Accept-Encoding") {
				return
			}
		}
	}
	header.Add("Vary", "Accept-Encoding")
}

func handler(files fs.FS, snapshot bool) http.Handler {
	// Bundled files are immutable for this process: read/hash each published file
	// once. Explicit external clients are reread so edits cannot retain stale tags.
	var cached map[string]clientFile
	if snapshot {
		cached = make(map[string]clientFile)
		remaining := maxGzipCacheBytes
		fs.WalkDir(files, ".", func(name string, entry fs.DirEntry, err error) error {
			if err == nil && !entry.IsDir() && published(name) {
				if file, err := readClientFile(files, name); err == nil {
					if name != "art/login.png" {
						file.gzip = compressedClientFile(file.content, remaining)
						remaining -= len(file.gzip)
					}
					cached[name] = file
				}
			}
			return nil
		})
	}
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("X-Content-Type-Options", "nosniff")
		if r.Method != http.MethodGet && r.Method != http.MethodHead {
			w.Header().Set("Allow", "GET, HEAD")
			http.Error(w, "method not allowed", http.StatusMethodNotAllowed)
			return
		}
		name := strings.TrimPrefix(r.URL.Path, "/")
		if name == "" {
			name = "index.html"
		}
		if !published(name) {
			http.NotFound(w, r)
			return
		}
		file, ok := cached[name]
		var err error
		if !snapshot {
			file, err = readClientFile(files, name)
		} else if !ok {
			err = fs.ErrNotExist
		}
		if err != nil {
			if name == "index.html" {
				w.Header().Set("Cache-Control", "no-store")
				http.Error(w, "client unavailable: run scripts/build-linux.sh", http.StatusServiceUnavailable)
			} else {
				http.NotFound(w, r)
			}
			return
		}
		if name == "index.html" {
			w.Header().Set("Cache-Control", "no-store")
			w.Header().Set("Content-Type", "text/html; charset=utf-8")
		} else {
			// Query versions are generated by the client builder. Revalidation also
			// protects unversioned requests across binary-only upgrades.
			w.Header().Set("Cache-Control", "no-cache")
			if name == "art/login.png" {
				w.Header().Set("Content-Type", "image/png")
			} else {
				w.Header().Set("Content-Type", "text/javascript; charset=utf-8")
			}
		}
		w.Header().Set("ETag", file.etag)
		content := file.content
		if name != "art/login.png" {
			varyEncoding(w.Header())
		}
		if len(file.gzip) > 0 && AcceptsGzip(strings.Join(r.Header.Values("Accept-Encoding"), ",")) {
			// Range bytes refer to the decoded script; serving part of a gzip
			// stream would produce an invalid program. Preserve identity ranges.
			if r.Header.Get("Range") != "" {
				r = r.Clone(r.Context())
				r.Header.Del("Range")
			}
			content = file.gzip
			w.Header().Set("Content-Encoding", "gzip")
			w.Header().Set("Content-Length", strconv.Itoa(len(content)))
		}
		http.ServeContent(w, r, name, time.Time{}, bytes.NewReader(content))
	})
}
